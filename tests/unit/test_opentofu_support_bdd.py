# --- Given steps ---


@given("a workspace directory exists", target_fixture="workspace_dir")
def workspace_dir(tmp_path: Path) -> Path:
    return tmp_path


@given(
    parsers.parse('the lockfile was generated by "{tool}"'),
    target_fixture="workspace_dir",
)
def lockfile_generated_by(workspace_dir: Path, tool: str) -> Path:
    (workspace_dir / ".terraform.lock.hcl").write_text(
        f'# This file is maintained automatically by "{tool}".\n'
    )
    return workspace_dir


@given(
    parsers.parse('the file "{filename}" exists with content "{content}"'),
    target_fixture="workspace_dir",
)
def file_with_content(workspace_dir: Path, filename: str, content: str) -> Path:
    (workspace_dir / filename).write_text(content)
    return workspace_dir


