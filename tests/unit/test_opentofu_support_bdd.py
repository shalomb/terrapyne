@given(
    parsers.parse('the environment variable "{var}" is set to "{value}"'),
    target_fixture="env_override",
)
def env_var_set(var: str, value: str, monkeypatch) -> tuple[str, str]:
    monkeypatch.setenv(var, value)
    return (var, value)


# --- When steps ---


@when("the runner is detected", target_fixture="detection_result")
def detect_runner_normally(workspace_dir: Path):
    """Detect with binary check mocked to always succeed."""
    with patch("terrapyne.core.runner_detection.which", return_value="/usr/bin/fake"):
        try:
            return detect_runner(workspace_dir)
        except (RunnerNotFoundError, AmbiguousRunnerError) as e:
            return e


@when("the runner is detected without the binary available", target_fixture="detection_result")
def detect_runner_missing_binary(workspace_dir: Path):
    """Detect with which() returning None — binary not installed."""
    with patch("terrapyne.core.runner_detection.which", return_value=None):
        try:
            return detect_runner(workspace_dir)
        except (RunnerNotFoundError, AmbiguousRunnerError) as e:
            return e


@when(
    parsers.parse('the runner is detected with force override "{runner}"'),
    target_fixture="detection_result",
)
def detect_runner_with_override(workspace_dir: Path, runner: str):
    return detect_runner(workspace_dir, force_runner=runner)


# --- Then steps ---


@then(parsers.parse('the detected runner is "{expected}"'))
def assert_runner_is(detection_result: str, expected: str):
    assert detection_result == expected


@then("detection fails because the binary is missing")
def assert_binary_missing(detection_result):
    assert isinstance(detection_result, RunnerNotFoundError)


@then("detection fails because the runner is ambiguous")
def assert_ambiguous(detection_result):
    assert isinstance(detection_result, AmbiguousRunnerError)


@when("a runner instance is created from the workspace", target_fixture="runner_instance")
def create_runner_instance(workspace_dir: Path):
    with (
        patch("terrapyne.core.runner_detection.which", return_value="/usr/bin/fake"),
        patch("terrapyne.core.local_binary.which", return_value="/usr/bin/fake"),
        patch.object(Terraform, "version", new_callable=lambda: property(lambda self: "1.9.0")),
        patch.object(OpenTofu, "version", new_callable=lambda: property(lambda self: "1.8.0")),
    ):
        return create_runner(workspace_dir)


@then("the instance is a Terraform runner")
def assert_terraform_instance(runner_instance):
    assert isinstance(runner_instance, Terraform)


@then("the instance is an OpenTofu runner")
def assert_opentofu_instance(runner_instance):
    assert isinstance(runner_instance, OpenTofu)
